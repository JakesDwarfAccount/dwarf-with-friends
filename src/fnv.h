#pragma once

// The one FNV-1a/64 byte fold and its two constants.

#include <cstddef>
#include <cstdint>

namespace dwf {

// NOT the published FNV-1a offset basis. Every hash this plugin has persisted or put on the wire
// was seeded with this value, so correcting it changes all of them at once.
constexpr uint64_t kFnvOffsetBasis = 1469598103934665603ull;
constexpr uint64_t kFnvPrime = 1099511628211ull;

inline uint64_t fnv1a(uint64_t h, const void* data, size_t n) {
    const uint8_t* p = static_cast<const uint8_t*>(data);
    for (size_t i = 0; i < n; ++i) { h ^= p[i]; h *= kFnvPrime; }
    return h;
}

} // namespace dwf
